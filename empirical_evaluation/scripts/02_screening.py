# ── LLM zero-shot screening ───────────────────────────────────────────────────
# Model for screening: gpt-4.1-mini (200k TPM, 500 RPM, 2M TPD on Tier 1)
# This avoids the 90,000 TPD cap on gpt-4o which would limit us to ~300 records/day.
SCREENING_MODEL = "gpt-4.1-mini"

SYSTEM_PROMPT = (
    "You are an expert systematic review screener. "
    "Given a title and abstract, decide whether the study meets the inclusion criteria. "
    "Respond with exactly one word: INCLUDE or EXCLUDE."
)

def llm_screen_record(title: str, abstract: str, criteria: str) -> str:
    """Return 'INCLUDE' or 'EXCLUDE' for a single record."""
    user_msg = (
        f"Inclusion criteria:\n{criteria}\n\n"
        f"Title: {title}\n\nAbstract: {abstract or '(no abstract)'}\n\n"
        "Decision (INCLUDE or EXCLUDE):"
    )
    for attempt in range(3):
        try:
            resp = client.chat.completions.create(
                model=SCREENING_MODEL,
                temperature=0,
                max_tokens=5,
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user",   "content": user_msg},
                ],
            )
            decision = resp.choices[0].message.content.strip().upper()
            return "INCLUDE" if "INCLUDE" in decision else "EXCLUDE"
        except Exception as e:
            if attempt < 2:
                time.sleep(5)
            else:
                print(f"  [LLM ERROR] {e}")
                return "EXCLUDE"

def llm_screen_case(df: pd.DataFrame, case_id: int) -> pd.Series:
    """Screen all records in df for a given case. Returns a Series of INCLUDE/EXCLUDE."""
    criteria = INCLUSION_CRITERIA.get(case_id, "Include if relevant to the topic.")
    decisions = []
    for _, row in tqdm(df.iterrows(), total=len(df), desc=f"  LLM screen case {case_id}"):
        dec = llm_screen_record(str(row.get("title", "")), str(row.get("abstract", "")), criteria)
        decisions.append(dec)
        time.sleep(0.12)  # ~500 RPM = 1 req/0.12s; stays within Tier 1 RPM limit
    return pd.Series(decisions, index=df.index)

# ── Active learning simulation ────────────────────────────────────────────────
# We use the LLM decisions as the "gold standard" labels for the AL simulation.
# The AL model is trained on an initial seed of 50 records (25 INCLUDE, 25 EXCLUDE)
# and evaluated at each iteration of 10 records until WSS@95 is reached.

def wss_at_95(y_true: np.ndarray, y_score: np.ndarray) -> float:
    """Work Saved over Sampling at 95% recall."""
    n = len(y_true)
    n_pos = y_true.sum()
    if n_pos == 0:
        return 0.0
    order = np.argsort(-y_score)
    y_sorted = y_true[order]
    cumsum = np.cumsum(y_sorted)
    threshold_idx = np.searchsorted(cumsum, 0.95 * n_pos)
    return (n - threshold_idx) / n - 0.05

def active_learning_simulation(df: pd.DataFrame, labels: np.ndarray) -> dict:
    """
    Simulate active learning on df with given binary labels.
    Returns dict with recall, precision, f1, wss95.
    """
    n = len(df)
    texts = (df["title"].fillna("") + " " + df["abstract"].fillna("")).tolist()
    # Seed: first 25 positives and 25 negatives
    pos_idx = np.where(labels == 1)[0][:25]
    neg_idx = np.where(labels == 0)[0][:25]
    if len(pos_idx) < 5 or len(neg_idx) < 5:
        return {"recall": None, "precision": None, "f1": None, "wss95": None,
                "n_screened": n, "note": "Insufficient positives for AL simulation"}
    seed_idx = np.concatenate([pos_idx, neg_idx])
    remaining_idx = np.array([i for i in range(n) if i not in set(seed_idx)])

    pipeline = Pipeline([
        ("tfidf", TfidfVectorizer(max_features=10000, sublinear_tf=True)),
        ("clf",   ComplementNB()),
    ])
    pipeline.fit([texts[i] for i in seed_idx], labels[seed_idx])

    screened_idx = list(seed_idx)
    batch_size = 10
    target_recall = 0.95

    while len(remaining_idx) > 0:
        proba = pipeline.predict_proba([texts[i] for i in remaining_idx])[:, 1]
        top_idx = remaining_idx[np.argsort(-proba)[:batch_size]]
        screened_idx.extend(top_idx)
        remaining_idx = np.array([i for i in remaining_idx if i not in set(top_idx)])
        # Retrain
        pipeline.fit([texts[i] for i in screened_idx], labels[screened_idx])
        # Check recall on screened set
        current_recall = labels[screened_idx].sum() / labels.sum() if labels.sum() > 0 else 0
        if current_recall >= target_recall:
            break

    # Final predictions: screened = predicted positive, rest = predicted negative
    y_pred = np.zeros(n, dtype=int)
    y_pred[screened_idx] = 1
    # WSS@95 using final model probabilities on full corpus
    all_proba = pipeline.predict_proba(texts)[:, 1]
    wss95 = wss_at_95(labels, all_proba)
    return {
        "recall":    round(recall_score(labels, y_pred, zero_division=0), 4),
        "precision": round(precision_score(labels, y_pred, zero_division=0), 4),
        "f1":        round(f1_score(labels, y_pred, zero_division=0), 4),
        "wss95":     round(wss95, 4),
        "n_screened": len(screened_idx),
    }

# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    summary_rows = []
    raw_files = sorted(RAW_DIR.glob("case_*.csv"))
    if not raw_files:
        print("[ERROR] No raw CSV files found. Run 01_retrieval.py first.")
        return

    for raw_path in raw_files:
        case_id = int(raw_path.stem.split("_")[1])
        slug    = "_".join(raw_path.stem.split("_")[2:])
        out_path = SCREENED_DIR / f"case_{case_id:02d}_{slug}_screened.csv"

        if out_path.exists():
            print(f"[SKIP] Case {case_id} already screened: {out_path.name}")
            df = pd.read_csv(out_path)
        else:
            print(f"\n[CASE {case_id:02d}] {slug}")
            df = pd.read_csv(raw_path)
            if df.empty:
                print("  [SKIP] Empty corpus.")
                continue

            # Step 1: LLM zero-shot screening
            print(f"  Running LLM zero-shot screening on {len(df)} records...")
            df["llm_decision"] = llm_screen_case(df, case_id)
            df.to_csv(out_path, index=False)
            print(f"  Saved: {out_path.name}")

        # Step 2: Active learning simulation using LLM labels as gold standard
        labels = (df["llm_decision"] == "INCLUDE").astype(int).values
        prevalence = labels.mean()
        print(f"  Prevalence (LLM): {prevalence:.1%} ({labels.sum()} / {len(labels)})")
        al_metrics = active_learning_simulation(df, labels)

        # LLM screening metrics vs itself (trivially 1.0) — we report AL vs LLM gold
        llm_recall    = 1.0  # LLM is the gold standard here
        llm_precision = prevalence  # all positives retrieved, precision = prevalence
        llm_f1        = 2 * llm_precision / (1 + llm_precision) if llm_precision > 0 else 0.0

        row = {
            "case_id":           case_id,
            "slug":              slug,
            "n_total":           len(df),
            "n_included_llm":    int(labels.sum()),
            "prevalence":        round(prevalence, 4),
            "llm_recall":        round(llm_recall, 4),
            "llm_precision":     round(llm_precision, 4),
            "llm_f1":            round(llm_f1, 4),
            "al_recall":         al_metrics.get("recall"),
            "al_precision":      al_metrics.get("precision"),
            "al_f1":             al_metrics.get("f1"),
            "al_wss95":          al_metrics.get("wss95"),
            "al_n_screened":     al_metrics.get("n_screened"),
        }
        summary_rows.append(row)
        print(f"  AL WSS@95: {al_metrics.get('wss95')} | AL Recall: {al_metrics.get('recall')}")

    summary_df = pd.DataFrame(summary_rows)
    summary_path = OUTPUTS_DIR / "screening_summary.csv"
    summary_df.to_csv(summary_path, index=False)
    print(f"\nScreening summary saved to {summary_path}")

if __name__ == "__main__":
    main()
