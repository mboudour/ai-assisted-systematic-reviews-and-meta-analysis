"""
02_screening.py
---------------
Screens all 20 case study corpora using two methods:
  1. Active learning (TF-IDF + Naive Bayes, uncertainty sampling via ASReview simulation)
  2. LLM zero-shot screening (gpt-4.1-mini, temperature=0)

Model choice rationale:
  gpt-4.1-mini is used for screening because it has 200,000 TPM, 500 RPM, and 2,000,000 TPD
  on Tier 1 accounts — sufficient for 100,000+ records without hitting daily token limits.
  gpt-4o is reserved for the smaller extraction/judge step in 03_extraction.py.

For each case the script:
  - Loads the deduplicated CSV from data/raw/
  - Runs the active learning simulation (requires a labelled seed set generated by LLM)
  - Runs LLM zero-shot screening on all records
  - Saves per-case screening results to data/screened/
  - Appends metrics to outputs/screening_summary.csv

Run:
    python scripts/02_screening.py

Requires: api_keys.env in the project root, data/raw/ populated by 01_retrieval.py
"""

